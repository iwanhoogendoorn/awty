const KIND_BY_ID = new Map(KINDS.map((k) => [k.id, k]));

export function kindDef(id: string | undefined): KindDef {
  return KIND_BY_ID.get((id ?? "") as TripKind) ?? KINDS[0];
}

export function isTripKind(value: unknown): value is TripKind {
  return typeof value === "string" && KIND_BY_ID.has(value as TripKind);
}

