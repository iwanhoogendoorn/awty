/** A trip as read back out of the vault. */
export interface Trip {
  file: TFile;
  /** Folder holding the trip note and its sub-notes. */
  folderPath: string;
  title: string;
  kind: TripKind;
  country: string;
  city: string;
  venue: string;
  /** ISO YYYY-MM-DD. */
  startDate: string;
  /** ISO YYYY-MM-DD; equal to startDate for single-day kinds. */
  endDate: string;
  status: TripStatus;
  /** Who is going. Drives packing quantities and the per-person cost split. */
  travellers: string[];
  /** Where you are leaving from — a trip has two ends, not one. */
  originCity: string;
  originAirport: string;
  /** Budget for the whole trip, or null when none was set. */
  budgetTotal: number | null;
}

/** The form payload shared by the new-trip and edit-trip modals. */
export interface TripDraft {
  title: string;
  kind: TripKind;
  country: string;
  city: string;
  venue: string;
  startDate: string;
  endDate: string;
  notes: string;
  subNotes: SubNoteId[];
  travellers: string[];
  originCity: string;
  originAirport: string;
  /** Budget for the whole trip, asked once and reused everywhere. */
  budgetTotal: number | null;
}

export interface TravelPlannerSettings {
  /** Root folder holding every trip. */
  tripsFolder: string;
  /**
   * Folder name for a trip, relative to tripsFolder. Supports {year}, {month},
   * {start}, {end}, {title}, {city}, {country}, {kind}. Defaults to grouping by
   * year with a date prefix so a second visit to Tokyo doesn't collide with the
   * first — the 1.x layout used the bare destination and simply refused.
   */
  folderPattern: string;
  defaultCountry: string;
  defaultKind: TripKind;
  /** Per-kind sub-note selection, overriding KindDef.subNotes. */
  subNotesByKind: Record<TripKind, SubNoteId[]>;
  /** Emit a ```foodspot``` block in the Food sub-note. */
  foodSpotEnabled: boolean;
  /** Which Food Spot view the generated block requests. */
  foodSpotView: "cards" | "list" | "table" | "shortlist";
  /** Ask before deleting a trip. Off means the confirm modal is skipped. */
  confirmDelete: boolean;
  /** Show past trips in the sidebar. */
  showPastTrips: boolean;
  /** Currency used when a booking or trip doesn't name its own. */
  defaultCurrency: string;
  /** Subfolder inside a trip where booking and expense notes live. */
  bookingsFolder: string;
  /** Subfolder inside a trip where attachments are copied. */
  attachmentsFolder: string;
  /**
   * Travel times call the Google Maps web services, which bill per request.
   * Off by default so nothing reaches the network — let alone the user's
   * billing account — until they switch it on and supply a key.
   */
  travelTimesEnabled: boolean;
  googleApiKey: string;
  /** Which modes to look up. Each mode is a separate billed request. */
  travelModes: TravelMode[];
  /** Airlines pinned to the top of the flight wizard picker. */
  starredAirlines: string[];
  /** Airports pinned to the top of the from/to pickers. */
  starredAirports: string[];
  /** Passports the party travels on, used for the visa check. */
  passportCountries: string[];
  /** Check Dutch government travel advice for the destination. */
  travelAdviceEnabled: boolean;
  /** Cost categories you added yourself, alongside the built-in ones. */
  customCategories: string[];
  /** Where you normally travel from, used to pre-fill the origin of a new trip. */
  homeCity: string;
  homeAirport: string;
  /** Everyone who might come along; a new trip starts with the first of these. */
  household: string[];
}

/** Google travel modes; duplicated here to keep the settings type dependency-free. */
export type TravelMode = "driving" | "transit" | "walking";

