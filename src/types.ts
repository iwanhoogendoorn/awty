import type { TFile } from "obsidian";

/**
 * A trip is anything that needs planning around a date and a place — a
 * fortnight in Japan, a Saturday in Ghent, or doors-at-19:00 in Tilburg.
 */
export type TripKind = "holiday" | "city-break" | "day-trip" | "concert" | "event" | "business";

export type TripStatus = "current" | "upcoming" | "past";

/**
 * `event-details` is no longer created: a concert is a trip with one headline
 * activity, and having both meant the same venue and tickets could be recorded
 * in two places. The id stays so notes made by older versions still read.
 */
export type SubNoteId =
  | "itinerary"
  | "packing"
  | "accommodation"
  | "budget"
  | "food"
  | "event-details"
  | "transport";

export interface KindDef {
  id: TripKind;
  label: string;
  /** Lucide icon name, used in the sidebar and the kind picker. */
  icon: string;
  /** Single-day kinds hide the end-date field entirely; end === start. */
  singleDay: boolean;
  /** Pre-selected length in days when you pick this kind in the new-trip modal. */
  defaultDurationDays: number;
  /** Sub-notes generated by default. Overridable per kind in settings. */
  subNotes: SubNoteId[];
  /** Concerts and events have a venue; a fortnight in Japan does not. */
  hasVenue: boolean;
}

